def _sanitize_characteristics(raw, spec: dict, composition: str) -> list[dict]:
    rows = _json(raw, [])
    output: list[dict] = []
    seen = set()
    label_map = {
        "Габарити": "Розміри",
        "Об'єм / варіанти": "Об'єм",
        "Об’єм / варіанти": "Об'єм",
        "Обсяг": "Об'єм",
    }
    for row in rows if isinstance(rows, list) else []:
        if not isinstance(row, dict):
            continue
        label = str(row.get("label") or "").strip()
        value = _strip_service_text(str(row.get("value") or ""))
        if not label or label.startswith("__"):
            continue
        if label.lower() in {"офіційне джерело", "джерело", "url", "призначення", "оригінальна назва"}:
            continue
        label = label_map.get(label, label)
        if label not in PUBLIC_CHARACTERISTIC_LABELS:
            continue
        if not value or "http://" in value.lower() or "https://" in value.lower():
            continue
        key = (label, value)
        if key not in seen:
            output.append({"label": label, "value": value})
            seen.add(key)

    def add(label: str, value: str):
        value = _translate(value).strip()
        if value and not any(x["label"] == label for x in output):
            output.append({"label": label, "value": value})

    add("Виробник", "PlantLogic")
    title = str(spec["title"])
    pid = str(spec["canonical_product_id"])
    model = ""
    for name in ("Zephyr V2", "Zephyr", "Hi-Grow", "Kratos", "Rivus", "Culti-base"):
        if name.lower() in (title + " " + " ".join(spec.get("manufacturer_titles") or [])).lower():
            model = name
            break
    if model:
        add("Модель", model)
    volume = re.search(r"(\d+(?:[.,]\d+)?)\s*л\b", title, flags=re.I)
    if volume:
        add("Об'єм", volume.group(1).replace(".", ",") + " л")
    if "кругл" in title.lower():
        add("Форма", "Кругла")
    elif "квадрат" in title.lower():
        add("Форма", "Квадратна")
    groove = re.search(r"U-пазами\s*Ø?\s*(\d+)\s*мм", title, flags=re.I)
    if groove:
        add("Діаметр U-пазів", "Ø" + groove.group(1) + " мм")
    leg = re.search(r"ніжках\s+(\d+)\s*(мм|см)", title, flags=re.I)
    if leg:
        add("Висота ніжок", leg.group(1) + " " + leg.group(2))
    if pid.startswith("plantlogic-micro-tube-stake-"):
        add("Довжина", "18 см")
    if pid == "plantlogic-nursery-tray-1302048":
        add("Кількість комірок", "72")
    if composition:
        add("Матеріал", composition.rstrip("."))
    add("Артикул виробника", ", ".join(str(x) for x in spec.get("manufacturer_product_numbers") or []))
    order = {name: i for i, name in enumerate([
        "Виробник", "Модель", "Об'єм", "Форма", "Розміри", "Діаметр U-пазів",
        "Висота ніжок", "Сумісність", "Колір", "Матеріал", "Кількість комірок",
        "Довжина", "Ширина", "Щільність", "Артикул виробника",
    ])}
    return sorted(output, key=lambda x: order.get(x["label"], 999))


def _content_for(spec: dict) -> dict:
    pid = str(spec["canonical_product_id"])
    if pid in SPECIAL:
        return SPECIAL[pid]
    unique = _other_unique_content(spec)
    if unique:
        return unique
    if spec.get("plantlogic_section") == "accessories":
        return _accessory_content(spec)
    if spec.get("plantlogic_section") == "strawberry":
        return _strawberry_content(spec)
    if "горщик" in str(spec["title"]).lower():
        return _pot_content(spec)
    if "основа" in str(spec["title"]).lower() or "мішок" in str(spec["title"]).lower():
        return _bag_base_content(spec)
    return _accessory_content(spec)


def apply(con: sqlite3.Connection) -> bool:
    spec = _load_spec()
    products = spec.get("canonical_products") or []
    if len(products) != 78:
        raise RuntimeError("PlantLogic canonical product count must be 78")
    for item in products:
        pid = str(item["canonical_product_id"])
        row = con.execute(
            "SELECT product_id,characteristics_json FROM products WHERE product_id=?",
            (pid,),
        ).fetchone()
        if not row:
            raise RuntimeError("missing canonical PlantLogic product: " + pid)
        content = _content_for(item)
        characteristics = _sanitize_characteristics(
            row["characteristics_json"], item, str(content.get("composition") or "")
        )
        con.execute(
            """
            UPDATE products SET
              short_description=?, description=?, application=?, composition=?,
              benefits_json=?, how_it_works=?, characteristics_json=?
            WHERE product_id=?
            """,
            (
                str(content["short_description"]).strip(),
                str(content["description"]).strip(),
                str(content["application"]).strip(),
                str(content.get("composition") or "").strip() or None,
                json.dumps(content.get("benefits") or [], ensure_ascii=False, separators=(",", ":")),
                str(content["how_it_works"]).strip(),
                json.dumps(characteristics, ensure_ascii=False, separators=(",", ":")),
                pid,
            ),
        )
    return True
