def _json(value, default):
    if value in (None, ""):
        return default
    if isinstance(value, (dict, list)):
        return value
    try:
        return json.loads(value)
    except Exception:
        return default


def _translate(text: str) -> str:
    value = str(text or "")
    replacements = [
        (r"\bopen-top grow bags?\b", "відкриті мішки для субстрату"),
        (r"\bgrow bags?\b", "мішки для субстрату"),
        (r"\bBag Bases\b", "основи для субстрату"),
        (r"\brootzone\b", "коренева зона"),
        (r"\bairflow\b", "повітрообмін"),
        (r"\bU-grooves?\b", "U-пази"),
        (r"\bshort legs\b", "короткі ніжки"),
        (r"\bAccessories\b", "аксесуари"),
        (r"\bPlantlogic\b", "PlantLogic"),
    ]
    for pattern, repl in replacements:
        value = re.sub(pattern, repl, value, flags=re.I)
    return re.sub(r"\s{2,}", " ", value).strip()


def _strip_service_text(text: str) -> str:
    value = _translate(text)
    sentences = re.split(r"(?<=[.!?])\s+", value)
    banned = (
        "дані та product # звірені", "характеристики звірені", "офіційна модель plantlogic",
        "офіційне джерело", "поточна сторінка виробника", "офіційна сторінка",
        "модель і product #", "не вигадуємо", "не специфікован", "використаному джерелі",
        "tech sheet", "product #",
    )
    kept = [s.strip() for s in sentences if s.strip() and not any(x in s.lower() for x in banned)]
    value = " ".join(kept)
    value = re.sub(r"https?://\S+", "", value)
    return re.sub(r"\s{2,}", " ", value).strip(" ;")


